//! filebridge desktop app: a thin Tauri client of `filebridge-service` (ADR 0008).
//!
//! Every command forwards to `filebridge_ipc::Client`; the TypeScript bindings in
//! `../src/bindings/` are generated from them by tauri-specta (`pnpm bindings`, or any debug
//! run of the app).

mod commands;
mod service;
mod tray;

use tauri::{Manager, WindowEvent};
use tauri_specta::{Builder, collect_events};

pub use service::{ConnectionChanged, Service, ServiceEvent};

/// Where the generated bindings go.
pub const BINDINGS_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/bindings/index.ts");

/// Commands and events, as both Tauri and the TypeScript exporter see them.
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(commands::all())
        .events(collect_events![ServiceEvent, ConnectionChanged])
        // Which job operation is allowed in which state, from the engine's own table: the dev
        // mock (`src/dev/mock.ts`) reads it instead of keeping a copy.
        .constant("JOB_OPERATIONS", filebridge_ipc::job_operations())
        .constant("PROTOCOL_VERSION", filebridge_ipc::PROTOCOL_VERSION)
        // Byte counts and millisecond timestamps (u64/i64) stay far below 2^53, so they are
        // exported as `number`. specta-typescript refuses 64-bit integers otherwise.
        .dangerously_cast_bigints_to_number()
}

/// Writes the TypeScript bindings.
pub fn export_bindings(builder: &Builder<tauri::Wry>) -> Result<(), String> {
    builder
        .export(
            specta_typescript::Typescript::default()
                .header("// Generated by tauri-specta from apps/desktop/src-tauri. DO NOT EDIT.\n"),
            BINDINGS_PATH,
        )
        .map_err(|e| e.to_string())
}

pub fn run() {
    tracing_init();
    let builder = specta_builder();
    #[cfg(debug_assertions)]
    if let Err(e) = export_bindings(&builder) {
        tracing::error!("could not export the TypeScript bindings: {e}");
    }

    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_notification::init())
        .plugin(tauri_plugin_opener::init())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            let handle = app.handle().clone();
            let service = Service::new(handle.clone());
            app.manage(service.clone());
            app.manage(tray::install(&handle)?);
            // Connect (and start the service if needed) right away, so the first screen
            // doesn't wait for it.
            tauri::async_runtime::spawn(async move {
                if let Err(e) = service.client().await {
                    tracing::warn!("filebridge-service: {e}");
                }
            });
            Ok(())
        })
        .on_window_event(|window, event| {
            // Closing the window hides it; sends continue in the service.
            if let WindowEvent::CloseRequested { api, .. } = event {
                api.prevent_close();
                let _ = window.hide();
            }
        })
        .run(tauri::generate_context!())
        .expect("error while running the filebridge window");
}

fn tracing_init() {
    // Logs go to stderr (`RUST_LOG=debug`); the service keeps its own log.
    let _ = tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env().unwrap_or_else(|_| "info".into()),
        )
        .with_writer(std::io::stderr)
        .try_init();
}

#[cfg(test)]
mod tests {
    /// `pnpm bindings` runs this to regenerate `src/bindings/index.ts`.
    #[test]
    fn export_bindings() {
        super::export_bindings(&super::specta_builder()).unwrap();
    }
}
