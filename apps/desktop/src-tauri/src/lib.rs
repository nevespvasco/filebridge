//! filebridge app. On desktop, a thin Tauri client of `filebridge-service` (ADR 0008): every
//! command forwards to `filebridge_ipc::Client`. On phones the engine runs in this process
//! (ADR 0014, [`engine`]) and the same commands call it directly. The TypeScript bindings in
//! `../src/bindings/` are generated from the commands by tauri-specta (`pnpm bindings`, or any
//! debug run of the app on desktop).

mod autostart;
mod commands;
mod native;
#[cfg(mobile)]
#[path = "engine.rs"]
mod service;
#[cfg(desktop)]
mod service;
#[cfg(desktop)]
mod tray;

use tauri::Manager;
use tauri_specta::{Builder, collect_events};

pub use service::{ConnectionChanged, Service, ServiceEvent};

/// Where the generated bindings go.
pub const BINDINGS_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/bindings/index.ts");

/// Commands and events, as both Tauri and the TypeScript exporter see them.
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(commands::all())
        .events(collect_events![ServiceEvent, ConnectionChanged])
        // Which job operation is allowed in which state, from the engine's own table: the dev
        // mock (`src/dev/mock.ts`) reads it instead of keeping a copy.
        .constant("JOB_OPERATIONS", filebridge_ipc::job_operations())
        .constant("PROTOCOL_VERSION", filebridge_ipc::PROTOCOL_VERSION)
        // Past this many direct entries a chosen folder shows "1000+".
        .constant("SOURCE_CHILDREN_CAP", filebridge_ipc::SOURCE_CHILDREN_CAP)
        // Byte counts and millisecond timestamps (u64/i64) stay far below 2^53, so they are
        // exported as `number`. specta-typescript refuses 64-bit integers otherwise.
        .dangerously_cast_bigints_to_number()
}

/// Writes the TypeScript bindings.
pub fn export_bindings(builder: &Builder<tauri::Wry>) -> Result<(), String> {
    builder
        .export(
            specta_typescript::Typescript::default()
                .header("// Generated by tauri-specta from apps/desktop/src-tauri. DO NOT EDIT.\n"),
            BINDINGS_PATH,
        )
        .map_err(|e| e.to_string())
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    tracing_init();
    // At login on Windows (the Run value, ADR 0028): start the engine, open nothing.
    #[cfg(desktop)]
    {
        let mut args = std::env::args_os().skip(1);
        if args.next().as_deref() == Some(filebridge_ipc::START_ENGINE_ARG.as_ref()) {
            if let Err(e) = service::start_engine(args.collect()) {
                tracing::error!("--start-engine: {e}");
                std::process::exit(1);
            }
            return;
        }
    }
    let builder = specta_builder();
    #[cfg(all(debug_assertions, desktop))]
    if let Err(e) = export_bindings(&builder) {
        tracing::error!("could not export the TypeScript bindings: {e}");
    }

    let app = tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_notification::init())
        .plugin(tauri_plugin_opener::init())
        .plugin(native::plugin())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            let handle = app.handle().clone();
            let service = Service::new(handle.clone());
            app.manage(service.clone());
            #[cfg(desktop)]
            app.manage(tray::install(&handle)?);
            // Connect (desktop: start the service if needed; phones: open the engine) right
            // away, so the first screen doesn't wait for it.
            tauri::async_runtime::spawn(async move {
                if let Err(e) = service.client().await {
                    tracing::warn!("engine: {}", e.message);
                }
            });
            Ok(())
        });
    #[cfg(desktop)]
    let app = app.on_window_event(|window, event| {
        // Closing the window hides it; sends continue in the service.
        if let tauri::WindowEvent::CloseRequested { api, .. } = event {
            api.prevent_close();
            let _ = window.hide();
        }
    });
    app.run(tauri::generate_context!())
        .expect("error while running the filebridge window");
}

fn tracing_init() {
    // Logs go to stderr (`RUST_LOG=debug`); the service keeps its own log. On Android stderr
    // is not shown: `adb logcat` has what the WebView and the plugin log, and the engine in the
    // app keeps its recent lines for "Copy log" (`service_log`) as the service does.
    use tracing_subscriber::prelude::*;
    let stderr = tracing_subscriber::fmt::layer()
        .with_writer(std::io::stderr)
        .with_filter(
            tracing_subscriber::EnvFilter::try_from_default_env().unwrap_or_else(|_| "info".into()),
        );
    #[cfg(mobile)]
    let _ = tracing_subscriber::registry()
        .with(stderr)
        .with(filebridge_host::RecentLog::global().layer())
        .try_init();
    #[cfg(desktop)]
    let _ = tracing_subscriber::registry().with(stderr).try_init();
}

